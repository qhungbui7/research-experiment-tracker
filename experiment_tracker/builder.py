def numeric_suffix(value: str) -> int:
    """Sort experiment_005 and round_010 by their numeric suffix."""
    match = re.search(r"(\d+)$", value)
    return int(match.group(1)) if match else 0


def issue_source(issue: Issue) -> tuple[str, str]:
    """Resolve the experiment and round that should own a tracker issue."""
    round_name = issue.round_name.strip()
    if "/" not in round_name:
        return issue.experiment, round_name
    parts = [part for part in round_name.split("/") if part]
    experiment = next((part for part in parts if part.startswith("experiment_")), issue.experiment)
    source_round = next((part for part in parts if part.startswith("round_")), round_name)
    return experiment, source_round


def clean_label(text: str, max_len: int) -> str:
    """Collapse long markdown text into one readable graph label line."""
    one_line = re.sub(r"\s+", " ", text.replace("`", "")).strip()
    if len(one_line) <= max_len:
        return one_line
    return one_line[: max_len - 1].rstrip() + "..."


def mermaid_label(*lines: str, max_len: int) -> str:
    """Build a Mermaid-safe multiline label."""
    cleaned = [clean_label(line, max_len) for line in lines if line]
    escaped = "<br/>".join(cleaned)
    return (
        escaped.replace("&", "&amp;")
        .replace('"', "&quot;")
        .replace("[", "&#91;")
        .replace("]", "&#93;")
    )


def node_id(prefix: str, *parts: str) -> str:
    """Create stable Mermaid/HTML node ids from human-readable parts."""
    raw = "__".join(part for part in parts if part)
    slug = re.sub(r"[^A-Za-z0-9_]+", "_", raw).strip("_").lower()
    digest = hashlib.sha1(raw.encode("utf-8")).hexdigest()[:8]
    return f"{prefix}_{slug[:48]}_{digest}"


class MermaidGraph:
    """Small helper for collecting Mermaid nodes and directed edges."""

    def __init__(self) -> None:
        self.nodes: dict[str, tuple[str, str]] = {}
        self.edges: set[tuple[str, str]] = set()

    def add_node(self, node: str, label: str, class_name: str) -> None:
        self.nodes[node] = (label, class_name)

    def add_edge(self, source: str, target: str) -> None:
        self.edges.add((source, target))

    def render(self) -> str:
        lines = [
            "%% Generated by research-experiment-tracker. Do not edit by hand.",
            "flowchart TD",
            "  classDef root fill:#f8fafc,stroke:#334155,stroke-width:2px,color:#0f172a;",
            "  classDef experiment fill:#e0f2fe,stroke:#0284c7,color:#0c4a6e;",
            "  classDef round fill:#dcfce7,stroke:#16a34a,color:#14532d;",
            "  classDef issue fill:#fff7ed,stroke:#ea580c,color:#7c2d12;",
            "  classDef file fill:#f1f5f9,stroke:#64748b,color:#334155;",
            "  classDef report fill:#ede9fe,stroke:#7c3aed,color:#3b0764;",
            "  classDef change fill:#fef9c3,stroke:#ca8a04,color:#713f12;",
            "  classDef next fill:#fee2e2,stroke:#dc2626,color:#7f1d1d;",
            "  classDef run fill:#dcfce7,stroke:#15803d,color:#14532d;",
            "  classDef snapshot fill:#fef3c7,stroke:#d97706,color:#78350f;",
        ]
        for node, (label, class_name) in sorted(self.nodes.items()):
            lines.append(f'  {node}["{label}"]')
            lines.append(f"  class {node} {class_name};")
        for source, target in sorted(self.edges):
            lines.append(f"  {source} --> {target}")
        return "\n".join(lines) + "\n"


def selected_experiments(experiments: list[Experiment], selected: set[str]) -> list[Experiment]:
    """Apply the optional --experiment filter."""
    if not selected:
        return experiments
    return [experiment for experiment in experiments if experiment.experiment in selected]


def issue_selected(issue: Issue, include_issues: str) -> bool:
    """Apply the issue visibility mode used by both output formats."""
    if include_issues == "none":
        return False
    if include_issues == "all":
        return True
    return issue.status.lower() in OPEN_STATUSES


def _sev_counts_for_experiments(
    issues: list[Issue],
    chosen_names: set[str],
    include_issues: str,
) -> dict[str, dict[str, int]]:
    """Compute open-issue severity counts per experiment."""
    counts: dict[str, dict[str, int]] = {}
    for issue in issues:
        if not issue_selected(issue, include_issues):
            continue
        if issue.experiment not in chosen_names:
            continue
        if issue.status.lower() not in OPEN_STATUSES:
            continue
        exp = issue.experiment
        counts.setdefault(exp, {"P0": 0, "P1": 0, "P2": 0, "other": 0})
        sev = issue.severity.upper()
        if sev in counts[exp]:
            counts[exp][sev] += 1
        else:
            counts[exp]["other"] += 1
    return counts


def _sev_badge(counts: dict[str, int]) -> str:
    parts = [f"{lbl}x{counts[lbl]}" for lbl in ("P0", "P1", "P2") if counts[lbl]]
    if counts.get("other"):
        parts.append(f"P3+x{counts['other']}")
    return "  ".join(parts)


def build_graph(
    experiments: list[Experiment],
    rounds: list[Round],
    issues: list[Issue],
    changes: list[ChangeEntry],
    selected: set[str],
    include_issues: str,
    include_changelog: bool,
    max_label_len: int,
    root_title: str = "Research Lineage",
    run_dirs: list[Path] | None = None,
    reviews_dir_prefix: str = "reports/reviews",
) -> str:
    """Build the static Mermaid graph used by IDEA_GRAPH.md."""
    graph = MermaidGraph()
    root = "root"
    graph.add_node(root, mermaid_label(root_title, max_len=max_label_len), "root")

    experiment_nodes: dict[str, str] = {}
    round_nodes: dict[tuple[str, str], str] = {}
    file_nodes: dict[str, str] = {}

    def add_file(path: str) -> str:
        if path not in file_nodes:
            file_node = node_id("file", path)
            file_nodes[path] = file_node
            graph.add_node(file_node, mermaid_label(path, max_len=max_label_len), "file")
        return file_nodes[path]

    chosen_experiments = selected_experiments(experiments, selected)
    chosen_names = {experiment.experiment for experiment in chosen_experiments}

    for experiment in sorted(chosen_experiments, key=lambda item: numeric_suffix(item.experiment)):
        exp_node = node_id("exp", experiment.experiment)
        experiment_nodes[experiment.experiment] = exp_node
        graph.add_node(
            exp_node,
            mermaid_label(experiment.experiment, experiment.subject, max_len=max_label_len),
            "experiment",
        )
        graph.add_edge(root, exp_node)
        for path in extract_paths(experiment.evidence_base, reviews_dir_prefix):
            graph.add_edge(exp_node, add_file(path))

    for round_info in sorted(
        (round_info for round_info in rounds if round_info.experiment in chosen_names),
        key=lambda item: (numeric_suffix(item.experiment), numeric_suffix(item.round_name)),
    ):
        exp_node = experiment_nodes.get(round_info.experiment)
        if not exp_node:
            continue
        round_node = node_id("round", round_info.experiment, round_info.round_name)
        round_nodes[(round_info.experiment, round_info.round_name)] = round_node
        graph.add_node(
            round_node,
            mermaid_label(round_info.round_name, round_info.date, round_info.trigger, max_len=max_label_len),
            "round",
        )
        graph.add_edge(exp_node, round_node)
        if round_info.report:
            report_node = node_id("report", round_info.experiment, round_info.round_name, round_info.report)
            graph.add_node(report_node, mermaid_label("Report", round_info.report, max_len=max_label_len), "report")
            graph.add_edge(round_node, report_node)
        for path in extract_paths(round_info.trigger + " " + round_info.report, reviews_dir_prefix):
            graph.add_edge(round_node, add_file(path))

    # Round-to-round chain within each experiment
    exp_rounds: dict[str, list[Round]] = {}
    for round_info in rounds:
        if round_info.experiment in chosen_names:
            exp_rounds.setdefault(round_info.experiment, []).append(round_info)
    for exp_name, exp_round_list in exp_rounds.items():
        sorted_rounds = sorted(exp_round_list, key=lambda r: numeric_suffix(r.round_name))
        for prev, curr in zip(sorted_rounds, sorted_rounds[1:]):
            prev_node = round_nodes.get((prev.experiment, prev.round_name))
            curr_node = round_nodes.get((curr.experiment, curr.round_name))
            if prev_node and curr_node:
                graph.add_edge(prev_node, curr_node)

    for issue in issues:
        source_exp, source_round = issue_source(issue)
        if issue.experiment not in chosen_names and source_exp not in chosen_names:
            continue
        if not issue_selected(issue, include_issues):
            continue
        source_node = round_nodes.get((source_exp, source_round), experiment_nodes.get(source_exp))
        if source_node is None:
            source_node = experiment_nodes.get(issue.experiment)
        if source_node is None:
            continue
        issue_node = node_id("issue", issue.issue_id, issue.experiment, issue.round_name)
        graph.add_node(
            issue_node,
            mermaid_label(
                f"{issue.issue_id} [{issue.severity} {issue.status}]",
                issue.title,
                issue.evidence,
                max_len=max_label_len,
            ),
            "issue",
        )
        graph.add_edge(source_node, issue_node)
        for path in extract_paths(issue.evidence, reviews_dir_prefix):
            graph.add_edge(issue_node, add_file(path))
        if issue.next_step:
            next_node = node_id("next", issue.issue_id, issue.next_step)
            graph.add_node(next_node, mermaid_label("Next", issue.next_step, max_len=max_label_len), "next")
            graph.add_edge(issue_node, next_node)
            for path in extract_paths(issue.next_step, reviews_dir_prefix):
                graph.add_edge(next_node, add_file(path))

    if include_changelog:
        for change in changes:
            matching_rounds = [round_pair for round_pair in change.rounds if round_pair[0] in chosen_names]
            matching_experiments = [name for name in change.experiments if name in chosen_names]
            if not matching_rounds and not matching_experiments:
                continue
            change_node = node_id("change", change.timestamp, change.title)
            graph.add_node(
                change_node,
                mermaid_label("Change", change.timestamp, change.title, max_len=max_label_len),
                "change",
            )
            for experiment_name, round_name in matching_rounds:
                parent = round_nodes.get((experiment_name, round_name), experiment_nodes.get(experiment_name))
                if parent:
                    graph.add_edge(parent, change_node)
            for experiment_name in matching_experiments:
                if not any(round_pair[0] == experiment_name for round_pair in matching_rounds):
                    parent = experiment_nodes.get(experiment_name)
                    if parent:
                        graph.add_edge(parent, change_node)
            for path in change.files:
                graph.add_edge(change_node, add_file(path))

    return graph.render()


